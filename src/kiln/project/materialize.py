"""`kiln dataset materialize <version> [--into <dir>]`: the training folder a trainer reads, from a frozen version.

A snapshot records which images a version holds; a trainer needs files with a caption beside each. This writes
only `<target>/training/`, `<target>/holdout/` and `<target>/_meta/materialized-<version>.json`, where the target
is `projects/<slug>/datasets/<version>/` (or `--into <dir>`, which must lie inside the instance). Each member is
copied with its caption as `<name>.txt`, on both sides: the holdout's validation loss needs its captions too.

Members with `root: images` are read from `images_root`, which stays read-only: a target inside it is refused,
and nothing is ever written there. A copy is checked against the member's sha256 before anything is written; a
missing or changed source, or a train member without a caption (a version brought in from another store can hold
one), refuses the whole run. A target that already holds files is refused too: the folder is generated, so the
refusal names the command for a fresh one, `kiln dataset materialize <version> --into <dir>`.

Where the latest materialisation of a version is: every run also writes its record to
`projects/<slug>/datasets/_meta/materialized-<version>.json`. `kiln dataset check`, `kiln next` and the training
preflight read the folder that record names, so a version materialised `--into` another folder is found without
naming the folder again; without that record they read `datasets/<version>/`.

The record has nine keys plus `schema`; `record_sha256_12` is the first 12 hex digits of sha256 over the record
without that key, `json.dumps(record, sort_keys=True)`. On an adopted project a record whose folders lie outside
its target (written by the host workspace before kiln) is reported as a note; its files are not counted.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

from kiln._common import hashing, store

from . import images as images_mod
from . import snapshot as snapshot_mod
from .model import SCHEMA, Project, ProjectError, now, why

NOTE = "Generated by kiln dataset materialize. Regenerate, do not hand-edit; the snapshot is the source of truth."
IMAGE_SUFFIXES = (".png", ".jpg", ".jpeg", ".webp")
SIDES = {"train": "training", "holdout": "holdout"}


def target_dir(project: Project, version: str, into: Path | None = None) -> Path:
    return Path(into).resolve() if into else (project.datasets_dir / version).resolve()


def record_path(base: Path, version: str) -> Path:
    return base / "_meta" / f"materialized-{version}.json"


def pointer_path(project: Project, version: str) -> Path:
    """The copy of the latest materialisation record of `version`, wherever that materialisation went."""
    return project.datasets_dir / "_meta" / f"materialized-{version}.json"


def record_stamp(record: dict) -> str:
    body = {k: v for k, v in record.items() if k != "record_sha256_12"}
    return hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()[:12]


def materialized_base(project: Project, version: str) -> Path:
    """The folder of the latest materialisation of `version`: the one the pointer record names, when that folder
    still holds its record; else `datasets/<version>/`."""
    pointer = pointer_path(project, version)
    if pointer.is_file():
        try:
            record = json.loads(pointer.read_text(encoding="utf-8"))
            train = (record.get("directories") or {}).get("train")
        except (OSError, ValueError, AttributeError):
            train = None
        if isinstance(train, str) and train:
            base = (project.instance.root / train).resolve().parent
            if record_path(base, version).is_file():
                return base
    return target_dir(project, version)


def _refuse_target(project: Project, version: str, base: Path) -> None:
    inst = project.instance
    writes = [base / side for side in (*SIDES.values(), "_meta")]
    if inst.under_images_root(base) or any(
            inst.images_root is not None and (d == inst.images_root or d in inst.images_root.parents) for d in writes):
        raise ProjectError(2, [f"REFUSED: {inst.shown(base)} is inside images_root, which is read-only until cutover",
                               "materialise under the project's datasets/ folder (the default target)"])
    if inst.relpath(base) is None:
        raise ProjectError(2, [f"REFUSED: --into must lie inside the instance folder (got {base.name})",
                               "the record names its folders relative to the instance root"])
    filled = [p for side in SIDES.values() if (base / side).is_dir() for p in (base / side).iterdir()]
    filled += [record_path(base, version)] if record_path(base, version).is_file() else []
    if filled:
        raise ProjectError(2, [f"REFUSED: {inst.shown(base)} already holds {len(filled)} file(s); the folder is "
                               "generated and never edited or emptied by hand",
                               f"  materialise into a fresh folder: kiln dataset materialize {version} --into <dir> "
                               "(a new folder inside the instance)",
                               f"  then: kiln dataset check {version} (it finds the newest materialisation)"])


@dataclass
class Written:
    record: dict
    path: Path
    counts: dict[str, int] = field(default_factory=dict)


def materialize(project: Project, version: str, into: Path | None = None) -> Written:
    snap = snapshot_mod.load(project, version)
    base = target_dir(project, version, into)
    _refuse_target(project, version, base)
    images = images_mod.records(project)
    plan: list[tuple[dict, Path, str]] = []
    problems = []
    names: dict[str, set[str]] = {side: set() for side in SIDES}
    for member in sorted(snap["members"], key=lambda m: (m["split"], m["image"])):
        if member["split"] not in SIDES:
            continue
        if member["split"] == "train" and not member.get("caption"):
            # training on an uncaptioned image teaches the trigger to mean nothing
            problems.append(f"{member['image']}: a train member without a caption in the snapshot; freeze a new "
                            "version once its caption is approved")
            continue
        record = images.get(member["image"])
        if record is None:
            problems.append(f"{member['image']}: not in images.jsonl")
            continue
        source = project.image_path(record)
        if not source.is_file():
            problems.append(f"{member['image']}: source missing ({record['root']}: {record['file']})")
            continue
        if hashing.sha256_file(source) != member["sha256"]:
            problems.append(f"{member['image']}: source bytes differ from the snapshot's sha256 ({record['file']})")
            continue
        name = source.name
        if name.lower() in names[member["split"]]:
            name = f"{member['image']}-{source.name}"
        names[member["split"]].add(name.lower())
        plan.append((member, source, name))
    if problems:
        raise ProjectError(2, ["REFUSED: the snapshot's sources do not check out; nothing was written",
                               *("  " + p for p in problems)])
    counts = {"train": 0, "holdout": 0}
    with project.lock():
        _refuse_target(project, version, base)  # a second materialise may have filled it meanwhile
        for member, source, name in plan:
            dest = base / SIDES[member["split"]] / name
            store.write_bytes(dest, source.read_bytes())  # read-only use of the source, whatever its root
            if member.get("caption"):
                store.write_text(dest.with_suffix(".txt"), str(member["caption"]).strip() + "\n")
            counts[member["split"]] += 1
        inst = project.instance
        record = {
            "schema": SCHEMA["materialized"],
            "snapshot_id": snap["id"],
            "snapshot_manifest_sha256": snap.get("manifest_sha256") or snap["members_sha256"],
            "materialized_at": now(),
            "caption_level": snap.get("caption_level", "medium"),
            "trigger_token": snap.get("trigger"),
            "counts": counts,
            "directories": {"train": inst.relpath(base / SIDES["train"]),
                            "holdout": inst.relpath(base / SIDES["holdout"])},
            "note": NOTE,
        }
        record["record_sha256_12"] = record_stamp(record)
        out = record_path(base, version)
        store.write_json(out, record)
        store.write_json(pointer_path(project, version), record)
    return Written(record=record, path=out, counts=counts)


@dataclass
class FolderCheck:
    """`dataset check` on one materialised version: what was found and what is wrong."""

    version: str
    base: Path
    found: bool = False
    counts: dict[str, int] = field(default_factory=dict)
    captions: dict[str, int] = field(default_factory=dict)
    problems: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    foreign: bool = False  # the record names folders outside its target: written by an adopted host, not kiln

    @property
    def ok(self) -> bool:
        return self.found and not self.problems and not self.foreign


def check_folder(project: Project, version: str, into: Path | None = None) -> FolderCheck:
    """Compare a materialised folder with its snapshot: counts, one caption per image on both sides, the record.

    Without `into` the folder is the latest materialisation of the version (`materialized_base`)."""
    snap = snapshot_mod.load(project, version)
    base = target_dir(project, version, into) if into else materialized_base(project, version)
    result = FolderCheck(version=version, base=base)
    rec_file = record_path(base, version)
    if not rec_file.is_file():
        return result
    result.found = True
    try:
        record = json.loads(rec_file.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        result.problems.append(f"the record {rec_file.name} does not parse: {why(exc, rec_file)}")
        return result
    if record.get("record_sha256_12") != record_stamp(record):
        result.problems.append(f"the record {rec_file.name} was edited after it was written (record_sha256_12)")
    if record.get("snapshot_id") != snap["id"]:
        result.problems.append(f"the record names {record.get('snapshot_id')}, not {snap['id']}")
    named = (record.get("directories") or {}).get("train")
    here = project.instance.relpath(base / SIDES["train"])
    if named != here:
        if project.adopted:
            result.foreign = True
            result.notes.append(f"the record names the folder {named}, written outside kiln (adopted project): its "
                                "files are not counted, and kiln does not train from it; materialise a kiln copy "
                                f"with kiln dataset materialize {version} --into <dir>")
            return result
        result.problems.append(f"the record names the folder {named}, not {here}")
    want = snap["counts"]
    for split, side in SIDES.items():
        folder = base / side
        pictures = [p for p in folder.iterdir() if p.suffix.lower() in IMAGE_SUFFIXES] if folder.is_dir() else []
        texts = {p.stem for p in folder.glob("*.txt")} if folder.is_dir() else set()
        result.counts[split] = len(pictures)
        result.captions[split] = sum(p.stem in texts for p in pictures)
        if len(pictures) != want.get(split, 0):
            result.problems.append(f"{side}: {len(pictures)} images, the snapshot has {want.get(split, 0)}")
        missing = [p.name for p in pictures if p.stem not in texts]
        if missing:
            result.problems.append(f"{side}: {len(missing)} image(s) without a caption file: "
                                   + " ".join(sorted(missing)[:10]))
    return result
